EXACT = {de: en for de, en in MAP.items() if " " not in de}
PHRASE = {de: en for de, en in MAP.items() if " " in de}


def translate(text: str, allow_inline: bool = True) -> str:
    """Übersetzt nur vollständige Treffer bzw. mehrteilige Phrasen – nie
    einzelne Wörter innerhalb längerer Wörter."""
    stripped = text.strip()
    if stripped in EXACT:
        lead = text[: len(text) - len(text.lstrip())]
        trail = text[len(text.rstrip()):]
        return lead + EXACT[stripped] + trail
    out = text
    if allow_inline:
        for de, en in sorted(PHRASE.items(), key=lambda kv: -len(kv[0])):
            if de in out:
                out = out.replace(de, en)
    return out


STR_LIT = re.compile(r'"([^"\n]*)"|\'([^\'\n]*)\'|`([^`]*)`', re.S)
JSX_TEXT = re.compile(r">([^<>{}()\n]{2,})(?=<|\{)")
# Textläufe zwischen JSX-/Template-Grenzen; schließt Anführungszeichen,
# Klammern und Backticks aus, damit keine Attribut- oder Codeteile getroffen werden.
RUN = re.compile(r'[^<>{}`"\'=\n]+')


def rewrite_file(path: pathlib.Path) -> bool:
    src = path.read_text(encoding="utf-8")
    out = []

    def lit(m):
        g = m.group(0)
        body = m.group(1) if m.group(1) is not None else m.group(2) if m.group(2) is not None else m.group(3)
        if not body:
            return g
        new = translate(body)
        return g.replace(body, new, 1)

    def jsx(m):
        return ">" + translate(m.group(1), allow_inline=False)

    new = STR_LIT.sub(lit, src)
    new = JSX_TEXT.sub(jsx, new)

    # Mehrzeilige JSX-Texte: Zeilenweise Textläufe übersetzen, Kommentarzeilen
    # bleiben unberührt.
    out_lines = []
    for line in new.split("\n"):
        if line.lstrip().startswith(("//", "*", "/*")):
            out_lines.append(line)
            continue
        if any(ord(ch) > 127 for ch in line) or " " in line:
            def run_sub(m):
                chunk = m.group(0)
                if not any(k in chunk for k in PHRASE):
                    return chunk
                return translate(chunk)
            line = RUN.sub(run_sub, line)
        out_lines.append(line)
    new = "\n".join(out_lines)
    # Mehrzeilige JSX-Labels, die alleine auf ihrer Zeile stehen.
    lines = []
    for line in new.split("\n"):
        stripped = line.strip()
        if (
            stripped in EXACT
            and not any(c in stripped for c in '"\'`{};<>=')
            and line != stripped
        ):
            indent = line[: len(line) - len(line.lstrip())]
            line = indent + EXACT[stripped]
        lines.append(line)
    new = "\n".join(lines)
    if new != src:
        path.write_text(new, encoding="utf-8")
        return True
    return False


def main() -> None:
    root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")
    changed = 0
    for p in root.rglob("*"):
        if p.suffix in {".ts", ".tsx"} and "node_modules" not in p.parts:
            if rewrite_file(p):
                changed += 1
    print(f"{changed} Dateien geändert")


if __name__ == "__main__":
    main()
